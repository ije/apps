globalThis.browserTestsDone = false;
(async () => {
  const assert = (value, message) => { if (!value) throw Error(message); };
  const calls = [], events = [];
  let nextId = 0;
  const api = __appsBrowser((...args) => {
    calls.push(args);
    if (args[0] === 'browser.create') return ++nextId;
    if (args[0] === 'browser.poll') return events.splice(0);
  }, __apps.events.EventEmitter);
  const first = api.contentView({ id: 1, isDestroyed: () => false }, {});
  const second = api.contentView({ id: 2, isDestroyed: () => false }, {});
  const view = new api.WebContentsView({ webPreferences: { partition: 'persist:test', javascript: false, devTools: false } });
  const contents = view.webContents;
  assert(view instanceof api.View && contents !== view, 'View and WebContents are separate');
  assert(!['attachTo', 'loadURL', 'loadHTML', 'executeJavaScript', 'destroy', 'session'].some(key => key in view), 'Page APIs belong on WebContents');
  assert(Object.getOwnPropertyDescriptor(view, 'webContents').writable === false, 'WebContents is read only');
  assert(JSON.stringify(calls[0]) === JSON.stringify(['browser.create', { partition: 'persist:test', javascript: false, inspectable: false, navigation: true }]), 'Map webPreferences to the native browser');
  for (const webPreferences of [{ preload: '/x.js' }, { nodeIntegration: true }, { contextIsolation: false }, { sandbox: false }, { unknown: 1 }, { partition: 1 }]) {
    let error;
    try { new api.WebContentsView({ webPreferences }); } catch (caught) { error = caught; }
    assert(error?.message === 'Unsupported webPreferences option: ' + Object.keys(webPreferences)[0], 'Reject unsafe webPreferences: ' + JSON.stringify(webPreferences));
  }
  new api.WebContentsView({ webPreferences: { nodeIntegration: false, contextIsolation: true, sandbox: true, webSecurity: true, preload: undefined } }).webContents.close();
  let changed = 0;
  view.on('bounds-changed', () => changed++);
  view.setBounds({ x: 10, y: 20, width: 300, height: 200 });
  view.setBounds(view.getBounds());
  const bounds = view.getBounds(); bounds.width = 1;
  assert(changed === 1 && view.getBounds().width === 300, 'Bounds events and copies');
  first.addChildView(view);
  const other = new api.WebContentsView();
  first.addChildView(other);
  first.addChildView(view);
  assert(first.children[0] === other && first.children[1] === view, 'Readding a child brings it to the top');
  first.addChildView(view, 0);
  assert(first.children[0] === view && first.children.length === 2, 'Indexed order without duplicates');
  first.children.pop();
  assert(first.children.length === 2, 'Child list is a copy');
  second.addChildView(view);
  assert(first.children.length === 1 && second.children[0] === view, 'Moving a view changes its parent');
  calls.length = 0;
  first.removeChildView(view);
  assert(calls.length === 0, 'Removing a non-child does nothing');
  second.removeChildView(view);
  assert(calls.some(args => args[0] === 'browser.detach' && args[1] === contents.id) && !contents.isDestroyed(), 'Removal detaches without destroying WebContents');
  const group = new api.View();
  group.setBounds({ x: 30, y: 40, width: 500, height: 400 });
  group.addChildView(view);
  second.addChildView(group);
  assert(calls.some(args => args[0] === 'browser.bounds' && args[1] === contents.id && args[2].join() === '40,60,300,200'), 'Child bounds are relative to the parent');
  let cycle = false;
  try { view.addChildView(group); } catch { cycle = true; }
  assert(cycle && second.children[0] === group, 'Reject cycles without changing the tree');
  group.setVisible(false);
  assert(!group.getVisible() && view.getVisible(), 'Visibility is local to each view');
  assert(calls.at(-1)[2] === 'visible' && calls.at(-1)[3] === false, 'Hide native descendants');
  group.setVisible(true);
  assert(calls.at(-1)[3] === true, 'Restore native visibility');
  let pageLoaded = false, viewLoaded = false;
  contents.on('did-finish-load', () => { pageLoaded = true; });
  view.on('did-finish-load', () => { viewLoaded = true; });
  const loaded = contents.loadURL('https://example.test/');
  events.push({ view: contents.id, event: { type: 'did-finish-load', url: 'https://example.test/', title: 'Test' } });
  api.poll();
  await loaded;
  assert(pageLoaded && !viewLoaded && contents.getURL() === 'https://example.test/' && contents.getTitle() === 'Test', 'Navigation events belong to WebContents');
  let failure;
  contents.once('did-fail-load', (...args) => { failure = args; });
  const failed = contents.loadURL('https://missing.test/').then(() => false, error => error.message === 'Missing page');
  events.push({ view: contents.id, event: { type: 'did-fail-load', code: -105, error: 'Missing page', url: 'https://missing.test/' } });
  api.poll();
  assert(await failed, 'Navigation rejects on failure');
  assert(failure[1] === -105 && failure[2] === 'Missing page' && failure[3] === 'https://missing.test/' && failure[4] === true, 'Electron navigation error arguments');
  const file = contents.loadFile('page.html', { query: { q: 'a b' }, hash: 'section' });
  assert(calls.at(-1)[3].endsWith('/page.html?q=a+b#section'), 'loadFile supports query and hash');
  events.push({ view: contents.id, event: { type: 'did-finish-load' } });
  api.poll(); await file;
  const seen = [];
  contents.on('will-navigate', (event, url) => { seen.push('navigate:' + url); if (url.endsWith('blocked')) event.preventDefault(); });
  contents.on('dom-ready', () => seen.push('dom-ready'));
  contents.on('console-message', (event, level, message, line, source) => seen.push(['console', event.level, level, message, line, source].join(':')));
  contents.on('ipc-message', (event, channel, data) => seen.push(channel + ':' + data.text));
  contents.on('did-create-window', child => seen.push('window:' + child.id));
  calls.length = 0;
  for (const url of ['https://ok.test/', 'https://blocked']) events.push({ view: contents.id, event: { type: 'will-navigate', id: url.length, url } });
  events.push({ view: contents.id, event: { type: 'dom-ready' } }, { view: contents.id, event: { type: 'message', url: 'https://ok.test/', data: { kind: 'console', level: 'warn', args: ['a', '1'] } } }, { view: contents.id, event: { type: 'message', data: { kind: 'message', data: { text: 'hi' } } } });
  api.poll();
  assert(contents.getURL() === 'https://example.test/page.html?q=a+b#section' || !contents.getURL().includes('blocked'), 'will-navigate does not change the URL');
  assert(JSON.stringify(calls.filter(args => args[2] === 'decide').map(args => args[3])) === JSON.stringify([{ id: 16, allow: true }, { id: 15, allow: false }]), 'will-navigate decides with preventDefault');
  assert(seen.join('|') === 'navigate:https://ok.test/|navigate:https://blocked|dom-ready|console:warning:2:a 1:0:https://ok.test/|message:hi', 'Electron page events: ' + seen.join('|'));
  let opened;
  contents.setWindowOpenHandler(details => { opened = details.url; return { action: 'deny' }; });
  events.push({ view: contents.id, event: { type: 'window-open', url: 'https://popup.test/' } });
  calls.length = 0;
  api.poll();
  assert(opened === 'https://popup.test/' && !calls.some(args => args[0] === 'browser.create'), 'Denied windows do not open');
  contents.setWindowOpenHandler(() => ({ action: 'allow' }));
  events.push({ view: contents.id, event: { type: 'window-open', url: 'https://popup.test/' } });
  api.poll();
  assert(calls.some(args => args[0] === 'browser.create' && args[1].show === true) && calls.some(args => args[2] === 'loadURL' && args[3] === 'https://popup.test/') && seen.at(-1).startsWith('window:'), 'Allowed windows open in a new browser window');
  const results = [contents.executeJavaScript('undefined'), contents.executeJavaScript('throw 1')];
  const requests = calls.filter(args => args[2] === 'evaluate').map(args => args[3].id).slice(-2);
  events.push({ view: contents.id, event: { type: 'evaluation', id: requests[0] } }, { view: contents.id, event: { type: 'evaluation', id: requests[1], error: 'TypeError: inner' } });
  api.poll();
  assert(await results[0] === undefined, 'executeJavaScript keeps undefined');
  const thrown = await results[1].catch(error => error);
  assert(thrown.name === 'TypeError' && thrown.message === 'inner', 'executeJavaScript rejects with the page error');
  calls.length = 0;
  contents.openDevTools();
  assert(calls.length === 0, 'Respect webPreferences.devTools');
  const adopted = new api.WebContentsView({ webContents: contents });
  assert(adopted.webContents === contents && !calls.some(args => args[0] === 'browser.create'), 'Adopt existing WebContents');
  calls.length = 0;
  view.setBounds({ x: 1, y: 2, width: 3, height: 4 });
  assert(calls.length === 0, 'Only one view presents the adopted WebContents');
  first.addChildView(adopted);
  const evaluation = contents.executeJavaScript('1 + 1').then(() => false, () => true);
  const navigation = contents.loadURL('https://pending.test/').then(() => false, () => true);
  let destroyed = 0;
  contents.on('destroyed', () => destroyed++);
  contents.close(); contents.close();
  assert(contents.isDestroyed() && destroyed === 1 && await evaluation && await navigation, 'Closing settles pending work and destroys once');
  first.removeChildView(adopted);
  other.webContents.close();
  assert(!api.pending(), 'Closed WebContents stop polling');
  browserTestsDone = true;
})();
