globalThis.editorResult = 'pending';
(async () => {
  const assert = (value, message) => { if (!value) throw Error(message); };
  const root = document.querySelector('test-editor').attachShadow({ mode: 'open' });
  root.innerHTML = '<div contenteditable="plaintext-only"><span>hello </span><b>world</b></div>';
  const editor = root.firstChild, first = editor.firstChild.firstChild, last = editor.lastChild.firstChild;
  const selection = getSelection();
  editor.focus();
  assert(editor.isContentEditable && first.parentElement.isContentEditable, 'Plaintext editing host');
  let changes = 0;
  const changed = () => changes++;
  document.addEventListener('selectionchange', changed);
  selection.setBaseAndExtent(last, 4, first, 2);
  assert(selection.direction === 'backward' && selection.anchorNode === last && selection.anchorOffset === 4 && selection.focusNode === first && selection.focusOffset === 2, 'Backward selection endpoints');
  assert(selection.toString() === 'llo worl', 'Backward selection text');
  const range = selection.getRangeAt(0), composed = selection.getComposedRanges({ shadowRoots: [root] })[0];
  assert(range.startContainer === first && range.startOffset === 2 && range.endContainer === last && range.endOffset === 4, 'Ordered live range');
  assert(composed.startContainer === first && composed.endContainer === last, 'Ordered composed range');
  assert(selection.containsNode(editor.firstChild, true) && !selection.containsNode(editor.firstChild), 'Partial containment');
  selection.extend(first, 1);
  assert(selection.anchorNode === last && selection.anchorOffset === 4 && selection.toString() === 'ello worl', 'Extend preserves anchor');
  assert(changes === 0 && composed.startOffset === 2, 'Selection events are asynchronous and StaticRange is immutable');
  await new Promise(resolve => setTimeout(resolve, 0));
  assert(changes === 1, 'Selection changes are coalesced');
  selection.setBaseAndExtent(last, 4, first, 1);
  await new Promise(resolve => setTimeout(resolve, 0));
  assert(changes === 1, 'Unchanged selection does not loop');
  selection.collapseToStart();
  assert(selection.focusNode === first && selection.focusOffset === 1 && selection.isCollapsed, 'Collapse to ordered start');
  selection.getRangeAt(0).setStart(first, 3);
  assert(selection.focusOffset === 3 && selection.isCollapsed, 'Live selected range endpoints');
  selection.removeRange(selection.getRangeAt(0));
  assert(selection.rangeCount === 0 && selection.anchorOffset === 0 && selection.direction === 'none', 'Clear selection');
  let threw = false;
  try { selection.extend(first, 0); } catch (error) { threw = error.name === 'InvalidStateError'; }
  assert(threw, 'Extend empty selection throws');
  range.setStart(last, 3); range.setEnd(first, 1);
  assert(range.collapsed && range.startContainer === first, 'Range collapses crossed boundaries');
  document.removeEventListener('selectionchange', changed);

  const formatted = document.createElement('div'); formatted.innerHTML = '<b>one</b><i>two</i>'; document.body.append(formatted);
  const replacement = document.createRange(); replacement.setStart(formatted.firstChild.firstChild,0); replacement.setEnd(formatted.lastChild.firstChild,3);
  replacement.deleteContents(); replacement.insertNode(document.createTextNode('new'));
  assert(formatted.textContent === 'new' && replacement.startContainer.isConnected, 'Cross-node deletion retains an attached insertion point');
  formatted.remove();

  const inputs = [];
  const inspect = event => inputs.push(event);
  document.addEventListener('beforeinput', inspect);
  document.addEventListener('input', inspect);
  selection.collapse(last, 0);
  __appsDispatch('keydown', [], { nativeKey: 'delete' });
  assert(editor.textContent === 'hello orld', 'Forward deletion');
  assert(inputs[0].inputType === 'deleteContentForward' && inputs[0].data === null && inputs[0].composed && inputs[0].cancelable, 'Forward deletion beforeinput');
  const targets = inputs[0].getTargetRanges();
  assert(targets.length === 1 && targets[0] instanceof StaticRange && targets[0].startContainer === first && targets[0].startOffset === 6 && targets[0].endContainer === last && targets[0].endOffset === 1, 'Deletion target ranges');
  targets.length = 0;
  assert(inputs[0].getTargetRanges().length === 1 && inputs[1].getTargetRanges().length === 0, 'Target range array isolation');
  inputs.length = 0;
  __appsDispatch('keydown', [], { nativeKey: 'enter' });
  assert(inputs[0].inputType === 'insertParagraph' && inputs[0].data === null && editor.textContent === 'hello \norld', 'Paragraph insertion');
  inputs.length = 0;
  __appsDispatch('keydown', [], { nativeKey: 'enter', shiftKey: true });
  assert(inputs[0].inputType === 'insertLineBreak', 'Shift Enter');
  inputs.length = 0;
  __appsClipboard('paste', 'pasted');
  assert(inputs[0].inputType === 'insertFromPaste' && inputs[0].data === null && inputs[0].dataTransfer.getData('text/plain') === 'pasted', 'Paste input metadata');
  selection.selectAllChildren(editor);
  const copied = editor.textContent;
  inputs.length = 0;
  assert(__appsClipboard('cut') === copied && editor.textContent === '', 'Cut selection');
  assert(inputs[0].inputType === 'deleteByCut' && inputs[0].data === null, 'Cut input type');
  const cancel = event => event.preventDefault();
  editor.addEventListener('beforeinput', cancel);
  inputs.length = 0;
  __appsInput('blocked');
  assert(editor.textContent === '' && inputs.length === 1 && inputs[0].defaultPrevented, 'Canceled input never mutates or emits input');
  editor.removeEventListener('beforeinput', cancel);

  const keys = [];
  editor.addEventListener('keydown', event => keys.push(event));
  editor.addEventListener('keyup', event => keys.push(event));
  __appsDispatch('keydown', [], { nativeKey: 'f', keyChar: 'ƒ', altKey: true });
  __appsDispatch('keyup', [], { nativeKey: 'f', keyChar: 'ƒ', altKey: true });
  assert(keys[0].key === 'ƒ' && keys[0].code === 'KeyF' && keys[0].keyCode === 70 && keys[0].getModifierState('Alt') && keys[1].type === 'keyup', 'Native key fields and release');
  __appsDispatch('keydown', [], { nativeKey: 'pageup' });
  assert(keys.at(-1).key === 'PageUp' && keys.at(-1).code === 'PageUp', 'Navigation key names');
  __appsDispatch('modifiers', [], { shiftKey: true });
  __appsDispatch('modifiers', [], { shiftKey: false });
  assert(keys.at(-2).key === 'Shift' && keys.at(-2).type === 'keydown' && keys.at(-1).type === 'keyup', 'Modifier press and release');
  editor.addEventListener('keydown', cancel, { once: true });
  assert(__appsDispatch('keydown', [], { nativeKey: 'v', metaKey: true }) === false, 'Canceled shortcut blocks native paste');
  const primary = navigator.platform.includes('Mac') ? { metaKey: true } : { ctrlKey: true };
  editor.textContent = 'select all';
  assert(__appsDispatch('keydown', [], { nativeKey: 'a', ...primary }) === false && selection.toString() === 'select all', 'Select all default follows keydown');

  editor.textContent = 'AB'; selection.collapse(editor.firstChild, 1);
  const composition = [];
  for (const type of ['compositionstart','compositionupdate','beforeinput','input','compositionend']) editor.addEventListener(type, event => {
    composition.push([type,event.inputType,event.data]);
    if (type === 'beforeinput') {
      assert(event.inputType === 'insertCompositionText' && !event.cancelable && event.isComposing, 'Composition input flags');
      event.preventDefault();
    }
  }, { signal: (globalThis.compositionController ??= new AbortController()).signal });
  __appsInput('中', 1, 1, true, [1,1]);
  __appsDispatch('keydown', [], { nativeKey: 'enter' });
  assert(keys.at(-1).isComposing && editor.textContent === 'A中B', 'Composition keydown bypasses editing defaults');
  __appsInput('文', 1, 2);
  assert(editor.textContent === 'A文B' && __appsEditing().marked === null, 'Composition commit');
  assert(composition.map(event => event[0]).join() === 'compositionstart,compositionupdate,beforeinput,input,compositionupdate,beforeinput,input,compositionend', 'Composition event order');
  compositionController.abort();
  assert(__appsDispatch('keydown', [], { nativeKey: 'z', ...primary }) === false && editor.textContent === 'AB', 'Undo removes the committed composition');
  assert(__appsDispatch('keydown', [], { nativeKey: 'z', shiftKey: true, ...primary }) === false && editor.textContent === 'A文B', 'Redo commits it again');

  const input = document.querySelector('textarea'); input.focus();
  input.value = 'A😀e\u0301B'; input.setSelectionRange(5,5);
  inputs.length = 0;
  __appsDispatch('keydown', [], { nativeKey: 'backspace' });
  assert(input.value === 'A😀B' && input.selectionStart === 3 && inputs[0].getTargetRanges().length === 0, 'Grapheme deletion and text control target ranges');
  __appsDispatch('keydown', [], { nativeKey: 'left', shiftKey: true });
  assert(input.selectionStart === 1 && input.selectionEnd === 3 && input.selectionDirection === 'backward', 'Backward shift movement skips surrogate pair');
  __appsDispatch('keydown', [], { nativeKey: 'right', shiftKey: true });
  assert(input.selectionStart === 3 && input.selectionEnd === 3, 'Shift movement shrinks from focus');
  input.value = 'one two'; input.setSelectionRange(7,7); inputs.length = 0;
  __appsDispatch('keydown', [], { nativeKey: 'backspace', ...(navigator.platform.includes('Mac') ? { altKey: true } : { ctrlKey: true }) });
  assert(input.value === 'one ' && inputs[0].inputType === 'deleteWordBackward', 'Word deletion binding');
  input.setSelectionRange(3,1);
  assert(input.selectionStart === 1 && input.selectionEnd === 1, 'Reversed control bounds collapse to end');
  input.value = 'abcdef'; input.setSelectionRange(4,5); input.setRangeText('XYZ',1,3);
  assert(input.value === 'aXYZdef' && input.selectionStart === 5 && input.selectionEnd === 6, 'Replacement preserves selection after edit');
  input.setSelectionRange(1,1); input.setRangeText('Q',3,5);
  assert(input.selectionStart === 1 && input.selectionEnd === 1, 'Replacement preserves selection before edit');
  input.value = 'readonly'; input.readOnly = true; input.select(); __appsInput('bad');
  assert(input.value === 'readonly', 'Readonly input');
  input.readOnly = false;

  editor.textContent = 'pointer'; const text = editor.firstChild;
  const originalCaret = document.caretRangeFromPoint;
  document.caretRangeFromPoint = x => { const range = document.createRange(); range.setStart(text,x); return range; };
  editor.addEventListener('pointerdown', cancel, { once: true });
  __appsDispatch('pointerdown', [text._id], { pointerId:1, clientX:2, clientY:0 });
  assert(document.activeElement === input, 'Canceled pointerdown does not focus');
  let sawOldFocus = false;
  editor.addEventListener('pointerdown', () => sawOldFocus = document.activeElement === input, { once: true });
  __appsDispatch('pointerdown', [text._id], { pointerId:1, clientX:5, clientY:0 });
  __appsDispatch('pointermove', [text._id], { pointerId:1, clientX:1, clientY:0, buttons:1 });
  assert(sawOldFocus && selection.toString() === 'oint' && selection.direction === 'backward', 'Pointer default order and backward drag');
  __appsDispatch('pointerup', [text._id], { pointerId:1 });
  __appsDispatch('pointermove', [text._id], { pointerId:1, clientX:0, clientY:0 });
  assert(selection.focusOffset === 1, 'Pointer release stops selection');
  __appsDispatch('pointerdown', [text._id], { pointerId:1, clientX:5, clientY:0 });
  __appsDispatch('pointerup', [text._id], { pointerId:1, clientX:0, clientY:0 });
  assert(selection.toString() === 'point' && selection.direction === 'backward', 'Pointer release applies the final coalesced position');
  text.data = 'hello world again';
  selection.collapse(text,0);
  __appsDispatch('pointerdown', [text._id], { pointerId:1, clientX:8, clientY:0, detail:2 });
  __appsDispatch('pointerup', [text._id], { pointerId:1, clientX:8, clientY:0 });
  assert(selection.toString() === 'world', 'Double click keeps the entire clicked word after release');
  __appsDispatch('pointerdown', [text._id], { pointerId:1, clientX:8, clientY:0, detail:2 });
  __appsDispatch('pointermove', [text._id], { pointerId:1, clientX:9, clientY:0, buttons:1 });
  assert(selection.toString() === 'world', 'Moving within the double-clicked word preserves it');
  __appsDispatch('pointermove', [text._id], { pointerId:1, clientX:14, clientY:0, buttons:1 });
  assert(selection.toString() === 'world again', 'Double-click drag extends by whole words');
  __appsDispatch('pointerup', [text._id], { pointerId:1, clientX:1, clientY:0 });
  assert(selection.toString() === 'hello world' && selection.direction === 'backward', 'Double-click drag reverses from the original word');
  let doubleClicks = 0;
  editor.addEventListener('dblclick', e => { assert(e.detail === 2, 'Double-click detail'); doubleClicks++; });
  __appsDispatch('click', [text._id], { detail:1 });
  __appsDispatch('click', [text._id], { detail:2 });
  assert(doubleClicks === 1, 'The second click dispatches dblclick');
  text.data = 'first line\nsecond line\nthird line';
  __appsDispatch('pointerdown', [text._id], { pointerId:1, clientX:14, clientY:0, detail:3 });
  __appsDispatch('pointerup', [text._id], { pointerId:1, clientX:14, clientY:0 });
  assert(selection.toString() === 'second line\n', 'Triple click keeps the complete line after release');
  document.caretRangeFromPoint = originalCaret;
  const scroller = document.createElement('div'), item = document.createElement('span');
  scroller.style.overflow = 'auto'; scroller.append(item); document.body.append(scroller);
  Object.defineProperties(scroller, { clientHeight: { value:100 }, clientWidth: { value:100 } });
  scroller.getBoundingClientRect = () => new DOMRect(0,0,100,100);
  item.getBoundingClientRect = () => new DOMRect(20,20,10,10);
  item.scrollIntoView({ block:'nearest' });
  assert(scroller.scrollTop === 0 && scroller.scrollLeft === 0, 'Nearest scrolling preserves visible content');
  item.getBoundingClientRect = () => new DOMRect(20,150,10,10);
  item.scrollIntoView({ block:'nearest' });
  assert(scroller.scrollTop === 60, 'Nearest scrolling uses the closest edge');
  scroller.remove();
  const frames = [];
  let canceled;
  await new Promise(resolve => {
    requestAnimationFrame(time => {
      frames.push(time);
      cancelAnimationFrame(canceled);
      requestAnimationFrame(next => { assert(next > time, 'Nested animation callbacks wait for the next frame'); resolve(); });
    });
    requestAnimationFrame(time => frames.push(time));
    canceled = requestAnimationFrame(() => { throw Error('Canceled frame ran'); });
  });
  assert(frames.length === 2 && frames[0] === frames[1], 'Animation callbacks share a frame timestamp');
  document.removeEventListener('beforeinput', inspect);
  document.removeEventListener('input', inspect);
})().then(() => editorResult = 'ok', error => editorResult = String(error) + '\n' + error.stack);
